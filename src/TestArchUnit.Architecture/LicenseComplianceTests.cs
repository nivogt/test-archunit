/// <summary>
/// Architecture tests for validating license compliance and architecture constraints.
/// </summary>
public class LicenseComplianceTests
{
    private static readonly Architecture Architecture =
        new ArchLoader().LoadAssemblies(typeof(Architecture).Assembly).Build();

    /// <summary>
    /// Validates that no GPL 3 licensed libraries are used in the solution.
    /// 
    /// GPL 3 is a copyleft license that can impose viral licensing requirements.
    /// This test ensures the project uses only compatible open source licenses.
    /// </summary>
    [Fact]
    public void NoGpl3LicensedDependencies()
    {
        // List of known GPL 3 licensed NuGet packages that should NOT be used
        var gpl3LicensedPackages = new[]
        {
            "AGPL",
            "GPL-3",
            "GPLv3"
        };

        // Get all dependencies from the API project
        var apiAssembly = Architecture.GetAssembliesByName("TestArchUnit.API").FirstOrDefault();
        
        var rule = Types()
            .That()
            .ResideInAssembly(apiAssembly)
            .Should()
            .NotDependOnAny(Types()
                .That()
                .HaveName(x => x.Contains("GPL") || x.Contains("AGPL"))
            );

        // Execute the rule
        var violations = rule.Evaluate(Architecture).ToList();
        
        // Assert no violations
        Assert.Empty(violations);
    }

    /// <summary>
    /// Validates that only approved open source licenses are used.
    /// Approved licenses: MIT, Apache 2.0, BSD, ISC
    /// </summary>
    [Fact]
    public void OnlyApprovedLicensesUsed()
