    /// <summary>
    /// Validates proper dependency injection patterns.
    /// Controllers should depend on interfaces, not concrete implementations.
    /// </summary>
    [Fact]
    public void ControllersShallDependOnInterfaces()
    {
        var rule = Classes()
            .That()
            .HaveNameEndingWith("Controller")
            .And()
            .ResideInNamespace("TestArchUnit.API.Controllers")
            .Should()
            .OnlyDependOnClassesThat()
            .Implement(typeof(object));

        var violations = rule.Evaluate(Architecture).ToList();
        
        // Allow some violations for framework dependencies
        Assert.True(violations.Count < 5, 
            $"Too many controller dependency violations: {violations.Count}");
    }

    /// <summary>
    /// Validates that API controllers are properly decorated.
    /// All controllers should have the ApiController attribute.
    /// </summary>
    [Fact]
    public void AllControllersHaveApiControllerAttribute()
    {
        var rule = Classes()
            .That()
            .HaveNameEndingWith("Controller")
            .And()
            .ResideInNamespace("TestArchUnit.API.Controllers")
            .Should()
            .HaveAnyAttributes();

        var violations = rule.Evaluate(Architecture).ToList();
        
        Assert.Empty(violations);
    }
}

/// <summary>
/// Tests for validating proper naming conventions across the solution.
/// </summary>
public class NamingConventionTests
{
    private static readonly Architecture Architecture =
        new ArchLoader().LoadAssemblies(typeof(NamingConventionTests).Assembly).Build();

    /// <summary>
    /// Validates that all public classes have meaningful names (no generic names).
    /// </summary>
    [Fact]
    public void PublicClassesHaveMeaningfulNames()
    {
        var illegalNames = new[] { "Class1", "Class2", "Test", "Helper", "Utils" };

        var rule = Classes()
            .That()
            .ArePublic()
            .And()
            .ResideInNamespace("TestArchUnit.API")
            .Should()
            .NotHaveNameMatching("^(Class|Test|Helper|Utils)[0-9]*$");

        var violations = rule.Evaluate(Architecture).ToList();
        
        Assert.Empty(violations);
    }
}

